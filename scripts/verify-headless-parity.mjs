#!/usr/bin/env node
/**
 * verify-headless-parity.mjs — tests/golden/rolls.json, asserted in Chromium.
 *
 *   npm run verify:headless-parity              # browser must match the file
 *   npm run verify:headless-parity -- --update  # rewrite the file from Chromium
 *
 * The page imports the same `rollHeadless()` and golden-case module the Node
 * test uses (packages/dice-core/test/rollGoldens.ts), with a fetch-backed
 * AssetSource instead of the filesystem one. So a pass here plus
 * `npm run test:core` means: the browser and Node roll the same faces from the
 * same (expression, seed, world) — the contract an embedding (#315) relies on.
 * With --update the file comes from the browser and the Node test asserts it:
 * the "vice versa" direction.
 */
import { readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import * as prettier from 'prettier';

import { startDev } from '../tests/helpers/server.js';
import { diffGolden } from '../packages/dice-core/test/rollGoldens.ts';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GOLDEN = path.join(REPO_ROOT, 'tests/golden/rolls.json');
const PROBE = path.join(REPO_ROOT, 'src/__headless_parity_probe.js');
const PORT = 5199;
const UPDATE = process.argv.includes('--update');

const PROBE_SRC = `
import { fetchAssetSource } from 'dice-core';
import { loadWasmBuildInfo } from 'dice-core/wasm/SolverBuildId';
import { GOLDEN_CASES, GOLDEN_DT, runGoldenCase } from '/packages/dice-core/test/rollGoldens.ts';
import tavernWorld from '/tests/fixtures/tavern-world.json';

export async function run() {
    const assets = fetchAssetSource(location.origin + '/');
    const info = await loadWasmBuildInfo('wasm', assets);
    const vectors = [];
    for (const c of GOLDEN_CASES) vectors.push(await runGoldenCase(c, { assets, tavernWorld }));
    return { solverRevision: info.solver_revision ?? 0, dt: GOLDEN_DT, vectors };
}
`;

await writeFile(PROBE, PROBE_SRC);
const vite = await startDev({ port: PORT });
const browser = await chromium.launch();
let result;
const errors = [];
try {
    const page = await browser.newPage();
    page.on('pageerror', (ex) => errors.push(`pageerror: ${ex.message}`));
    page.on('console', (m) => {
        if (m.type() === 'error' || m.type() === 'warning') errors.push(`${m.type()}: ${m.text()}`);
    });
    // Any same-origin non-app URL: the probe module must not boot the tavern.
    await page.goto(`${vite.base}/packages/dice-core/src/wasm/physicsFlags.ts`, {
        waitUntil: 'domcontentloaded',
    });
    result = await page.evaluate(async () => {
        try {
            // @ts-ignore — written just above, served by vite.
            const m = await import('/src/__headless_parity_probe.js');
            return { ok: true, ...(await m.run()) };
        } catch (ex) {
            return { ok: false, reason: String((ex && ex.stack) || ex) };
        }
    });
} finally {
    await browser.close();
    await vite.close();
    await rm(PROBE, { force: true });
}

if (!result?.ok) {
    console.error('[headless-parity] browser run failed:', result?.reason, errors);
    process.exit(1);
}

if (UPDATE) {
    const file = {
        version: 1,
        solverRevision: result.solverRevision,
        dt: result.dt,
        generatedBy: 'chromium',
        vectors: result.vectors,
    };
    const options = { ...(await prettier.resolveConfig(GOLDEN)), parser: 'json' };
    await writeFile(GOLDEN, await prettier.format(JSON.stringify(file), options));
    console.log(
        `[headless-parity] wrote ${result.vectors.length} vectors from Chromium → tests/golden/rolls.json`
    );
    process.exit(0);
}

const golden = JSON.parse(await readFile(GOLDEN, 'utf8'));
const problems = [];
if (golden.solverRevision !== result.solverRevision) {
    problems.push(
        `solver revision: file ${golden.solverRevision}, browser build ${result.solverRevision} — regenerate`
    );
}
if (golden.vectors.length !== result.vectors.length) {
    problems.push(`vector count: file ${golden.vectors.length}, browser ${result.vectors.length}`);
}
golden.vectors.forEach((want, i) => {
    const got = result.vectors[i];
    if (!got) return;
    const diff = diffGolden(want, got);
    if (diff) problems.push(diff);
});

if (problems.length) {
    console.error(`[headless-parity] FAILED (${problems.length}):\n  ${problems.join('\n  ')}`);
    process.exit(1);
}
console.log(
    `[headless-parity] PASSED — Chromium reproduces all ${result.vectors.length} golden rolls ` +
        `(file generated by ${golden.generatedBy}).`
);
