/**
 * tests/golden/rolls.json, asserted in Node. Chromium asserts the same file
 * through scripts/verify-headless-parity.mjs; see rollGoldens.ts.
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';
import { defaultPublicDir, fsAssetSource } from 'dice-core';
import { loadWasmBuildInfo } from 'dice-core/wasm/SolverBuildId';
import type { WorldFixture } from 'dice-core/wasm/WorldRecorder';
import {
    GOLDEN_CASES,
    diffGolden,
    runGoldenCase,
    type GoldenFile,
    type GoldenRecord,
} from './rollGoldens.js';
import { describeWasm } from './wasmGate.js';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const golden = JSON.parse(
    readFileSync(path.join(REPO_ROOT, 'tests/golden/rolls.json'), 'utf8')
) as GoldenFile;
const tavernWorld = JSON.parse(
    readFileSync(path.join(REPO_ROOT, 'tests/fixtures/tavern-world.json'), 'utf8')
) as WorldFixture;

it('golden file lists every case in rollGoldens.ts, in order', () => {
    expect(golden.version).toBe(1);
    expect(
        golden.vectors.map(({ expression, seed, world }) => ({ expression, seed, world }))
    ).toEqual(GOLDEN_CASES);
    // Every hull shape and every derived face sequence is pinned somewhere.
    const expressions = golden.vectors.map((v) => v.expression).join(' ');
    for (const die of ['d4', 'd6', 'd8', 'd10', 'd12', 'd20', 'd2', 'd3', 'd5', 'dF', 'd100']) {
        expect(expressions).toContain(die);
    }
});

it('every golden die settled on a real face', () => {
    for (const v of golden.vectors) {
        expect(v.faces.every((f) => f > 0)).toBe(true);
    }
});

describeWasm('golden rolls (Node)', () => {
    const assets = fsAssetSource(defaultPublicDir()!);

    it('was generated by this solver revision', async () => {
        const info = await loadWasmBuildInfo('wasm', assets);
        expect(
            info.solver_revision,
            'tests/golden/rolls.json is from another SOLVER_REVISION — run npm run golden:rolls'
        ).toBe(golden.solverRevision);
    });

    it(`reproduces all ${GOLDEN_CASES.length} vectors`, async () => {
        const mismatches: string[] = [];
        for (const want of golden.vectors) {
            const got: GoldenRecord = await runGoldenCase(want, { assets, tavernWorld });
            const diff = diffGolden(want, got);
            if (diff) mismatches.push(diff);
        }
        expect(mismatches).toEqual([]);
    });
});
